    private void cargarAlumnos() {
        jCbseleccion.removeAllItems();

        List<Alumno> alumnos = Principal.alumnoData.ListarAlumnos();

        for (Alumno alumno : alumnos) {
            jCbseleccion.addItem(alumno.toString());
        }
    }
